type ExcelExportTool struct{}

func (e ExcelExportTool) Name() string { return "export_excel" }
func (e ExcelExportTool) Description() string {
	return "Generates a beautifully styled multi-sheet BCG Excel report. Input must specify 'records' array of objects, 'question', and 'sql_query'."
}

func (e ExcelExportTool) ParameterSchema() map[string]any {
	return map[string]any{
		"type": "object",
		"properties": map[string]any{
			"records": map[string]any{
				"type": "array",
				"items": map[string]any{
					"type": "object",
				},
				"description": "The array of output rows/records to export.",
			},
			"question": map[string]any{
				"type":        "string",
				"description": "The user's natural language query.",
			},
			"sql_query": map[string]any{
				"type":        "string",
				"description": "The raw SQL query that produced the records.",
			},
		},
		"required": []string{"records", "question", "sql_query"},
	}
}

func (e ExcelExportTool) Call(ctx context.Context, input string) (string, error) {
	var payload struct {
		Records  []map[string]any `json:"records"`
		Question string           `json:"question"`
		SQL      string           `json:"sql_query"`
	}

	if err := json.Unmarshal([]byte(input), &payload); err != nil {
		return "", fmt.Errorf("failed to parse structured input JSON: %v. Raw input: %s", err, input)
	}

	// Handle empty records gracefully
	if len(payload.Records) == 0 {
		return "No records found to export to Excel.", nil
	}

	// Create a temp file to pass payload to python excel_generator.py
	tempFile, err := os.CreateTemp("", "ul_excel_payload_*.json")
	if err != nil {
		return "", fmt.Errorf("failed to create temp file: %v", err)
	}
	defer os.Remove(tempFile.Name())
	defer tempFile.Close()

	type pythonPayload struct {
		Records   []map[string]any `json:"records"`
		Question  string           `json:"question"`
		SQL       string           `json:"sql"`
		ExportDir string           `json:"export_dir"`
	}
	pData := pythonPayload{
		Records:   payload.Records,
		Question:  payload.Question,
		SQL:       payload.SQL,
		ExportDir: "./data/excel_exports",
	}

	enc := json.NewEncoder(tempFile)
	if err := enc.Encode(pData); err != nil {
		return "", fmt.Errorf("failed to encode payload: %v", err)
	}

	// Run Python Excel script
	cmd := exec.CommandContext(ctx, "python", "excel_generator.py", tempFile.Name())
	out, err := cmd.CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("python script execution failed: %v. Output: %s", err, string(out))
	}

	filename := strings.TrimSpace(string(out))
	lines := strings.Split(filename, "\n")
	filename = strings.TrimSpace(lines[len(lines)-1])

	downloadURL := fmt.Sprintf("http://localhost:%s/download/%s", getEnv("MCP_SERVER_PORT", "10015"), filename)
	return fmt.Sprintf("Excel report generated successfully!\nFilename: %s\nDownload Link: %s", filename, downloadURL), nil
}

// ============================================================================
// Streaming Callbacks Handler
// ============================================================================

type StreamCallback struct {
	callbacks.SimpleHandler
	OnLLMToken  func(token string)
	OnLLMEnd    func(res *llms.ContentResponse)
	OnToolStart func(input string)
	OnToolEnd   func(output string)
}

func (s *StreamCallback) HandleStreamingFunc(ctx context.Context, chunk []byte) {
	if s.OnLLMToken != nil {
		s.OnLLMToken(string(chunk))
	}
}

func (s *StreamCallback) HandleLLMGenerateContentEnd(ctx context.Context, res *llms.ContentResponse) {
	if s.OnLLMEnd != nil {
		s.OnLLMEnd(res)
	}
}

func (s *StreamCallback) HandleToolStart(ctx context.Context, input string) {
	if s.OnToolStart != nil {
		s.OnToolStart(input)
	}
}

func (s *StreamCallback) HandleToolEnd(ctx context.Context, output string) {
	if s.OnToolEnd != nil {
		s.OnToolEnd(output)
	}
}

