func loadEnv() {
	file, err := os.Open(".env")
	if err != nil {
		log.Println("Note: .env file not found, using system environment variables.")
		return
	}
	defer file.Close()

	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := strings.SplitN(line, "=", 2)
		if len(parts) == 2 {
			key := strings.TrimSpace(parts[0])
			value := strings.TrimSpace(parts[1])
			if (strings.HasPrefix(value, "\"") && strings.HasSuffix(value, "\"")) ||
				(strings.HasPrefix(value, "'") && strings.HasSuffix(value, "'")) {
				value = value[1 : len(value)-1]
			}
			os.Setenv(key, value)
		}
	}
}

func getEnv(key, defaultVal string) string {
	if val := os.Getenv(key); val != "" {
		return val
	}
	return defaultVal
}

// ============================================================================
// MCP Tool Adapter (Structured arguments)
// ============================================================================

type MCPToolWrapper struct {
	session *mcp.ClientSession
	name    string
	desc    string
	schema  map[string]any
}

func (w *MCPToolWrapper) ParameterSchema() map[string]any {
	return w.schema
}

func (w *MCPToolWrapper) Name() string        { return w.name }
func (w *MCPToolWrapper) Description() string { return w.desc }

func (w *MCPToolWrapper) Call(ctx context.Context, input string) (string, error) {
	var args any
	input = strings.TrimSpace(input)

	// Since we are using structured schemas, input is the raw JSON string generated by the LLM
	if strings.HasPrefix(input, "{") && strings.HasSuffix(input, "}") {
		var m map[string]any
		if err := json.Unmarshal([]byte(input), &m); err == nil {
			args = m
		} else {
			args = input
		}
	} else {
		// Fallback for simple raw string formats
		if w.name == "query_postgres" {
			args = map[string]any{
				"sql_query": input,
				"question":  "Executed via Go client agent",
			}
		} else {
			args = input
		}
	}

	params := &mcp.CallToolParams{
		Name:      w.name,
		Arguments: args,
	}

	res, err := w.session.CallTool(ctx, params)
	if err != nil {
		return "", err
	}

	if res.IsError {
		var sb strings.Builder
		for _, c := range res.Content {
			if tc, ok := c.(*mcp.TextContent); ok {
				sb.WriteString(tc.Text)
			}
		}
		return fmt.Sprintf("Error: %s", sb.String()), nil
	}

	var sb strings.Builder
	for _, c := range res.Content {
		if tc, ok := c.(*mcp.TextContent); ok {
			sb.WriteString(tc.Text)
		}
	}
	return sb.String(), nil
}

