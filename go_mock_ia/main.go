type CustomOpenAIAgent struct {
	LLM              llms.Model
	Tools            []tools.Tool
	OutputKey        string
	CallbacksHandler callbacks.Handler
	SystemPrompt     string
	History          []llms.ChatMessage
}

var _ agents.Agent = (*CustomOpenAIAgent)(nil)

func (a *CustomOpenAIAgent) GetInputKeys() []string  { return []string{"input"} }
func (a *CustomOpenAIAgent) GetOutputKeys() []string { return []string{a.OutputKey} }
func (a *CustomOpenAIAgent) GetTools() []tools.Tool  { return a.Tools }

func (a *CustomOpenAIAgent) Plan(
	ctx context.Context,
	intermediateSteps []schema.AgentStep,
	inputs map[string]string,
	options ...chains.ChainCallOption,
) ([]schema.AgentAction, *schema.AgentFinish, error) {
	var messages []llms.ChatMessage

	// 1. System Prompt
	messages = append(messages, llms.SystemChatMessage{Content: a.SystemPrompt})

	// 2. Conversation History
	messages = append(messages, a.History...)

	// 3. Human Message
	messages = append(messages, llms.HumanChatMessage{Content: inputs["input"]})

	// 4. Scratchpad (Intermediate steps)
	scratchPad := a.constructScratchPad(intermediateSteps)
	messages = append(messages, scratchPad...)

	// Convert chat messages to ContentPart slice
	mcList := make([]llms.MessageContent, len(messages))
	for i, msg := range messages {
		role := msg.GetType()
		text := msg.GetContent()

		var mc llms.MessageContent
		switch p := msg.(type) {
		case llms.ToolChatMessage:
			mc = llms.MessageContent{
				Role: role,
				Parts: []llms.ContentPart{llms.ToolCallResponse{
					ToolCallID: p.ID,
					Content:    p.Content,
				}},
			}
		case llms.AIChatMessage:
			if len(p.ToolCalls) > 0 {
				toolCallParts := make([]llms.ContentPart, 0, len(p.ToolCalls))
				for _, tc := range p.ToolCalls {
					toolCallParts = append(toolCallParts, llms.ToolCall{
						ID:           tc.ID,
						Type:         tc.Type,
						FunctionCall: tc.FunctionCall,
					})
				}
				mc = llms.MessageContent{
					Role:  role,
					Parts: toolCallParts,
				}
			} else {
				mc = llms.MessageContent{
					Role:  role,
					Parts: []llms.ContentPart{llms.TextContent{Text: text}},
				}
			}
		default:
			mc = llms.MessageContent{
				Role:  role,
				Parts: []llms.ContentPart{llms.TextContent{Text: text}},
			}
		}
		mcList[i] = mc
	}

	var stream func(ctx context.Context, chunk []byte) error
	if a.CallbacksHandler != nil {
		stream = func(ctx context.Context, chunk []byte) error {
			a.CallbacksHandler.HandleStreamingFunc(ctx, chunk)
			return nil
		}
	}

	callOpts := []llms.CallOption{
		llms.WithStreamingFunc(stream),
	}

	funcs := a.functions()
	callOpts = append(callOpts, llms.WithFunctions(funcs))

	log.Printf("CustomOpenAIAgent.Plan inputs: %+v", inputs)
	log.Printf("CustomOpenAIAgent.Plan sending %d messages:", len(mcList))
	for idx, mc := range mcList {
		log.Printf("  Message [%d] Role: %q", idx, mc.Role)
		for pIdx, part := range mc.Parts {
			switch p := part.(type) {
			case llms.TextContent:
				preview := p.Text
				if len(preview) > 200 {
					preview = preview[:200] + "..."
				}
				log.Printf("    Part [%d] TextContent: %s", pIdx, preview)
			case llms.ToolCall:
				log.Printf("    Part [%d] ToolCall: ID=%s, Name=%s, Args=%s", pIdx, p.ID, p.FunctionCall.Name, p.FunctionCall.Arguments)
			case llms.ToolCallResponse:
				preview := p.Content
				if len(preview) > 200 {
					preview = preview[:200] + "..."
				}
				log.Printf("    Part [%d] ToolCallResponse: ID=%s, Content=%s", pIdx, p.ToolCallID, preview)
			default:
				log.Printf("    Part [%d] Unknown Part: %T", pIdx, part)
			}
		}
	}

	res, err := a.LLM.GenerateContent(ctx, mcList, callOpts...)
	if err != nil {
		return nil, nil, err
	}

	return a.parseOutput(res)
}

func (a *CustomOpenAIAgent) functions() []llms.FunctionDefinition {
	res := make([]llms.FunctionDefinition, 0)
	for _, tool := range a.Tools {
		var params map[string]any
		if schematized, ok := tool.(interface{ ParameterSchema() map[string]any }); ok {
			params = schematized.ParameterSchema()
		} else {
			// Fallback schema for simple string tools
			params = map[string]any{
				"type": "object",
				"properties": map[string]any{
					"__arg1": map[string]any{"type": "string"},
				},
				"required": []string{"__arg1"},
			}
		}
		res = append(res, llms.FunctionDefinition{
			Name:        tool.Name(),
			Description: tool.Description(),
			Parameters:  params,
		})
	}
	return res
}

func (a *CustomOpenAIAgent) constructScratchPad(steps []schema.AgentStep) []llms.ChatMessage {
	if len(steps) == 0 {
		return nil
	}

	messages := make([]llms.ChatMessage, 0)
	var currentToolCalls []llms.ToolCall
	var currentLog string

	for i, step := range steps {
		if i == 0 || step.Action.Log != steps[i-1].Action.Log {
			if len(currentToolCalls) > 0 {
				messages = append(messages, llms.AIChatMessage{
					Content:   currentLog,
					ToolCalls: currentToolCalls,
				})
				for j := i - len(currentToolCalls); j < i; j++ {
					messages = append(messages, llms.ToolChatMessage{
						ID:      steps[j].Action.ToolID,
						Content: steps[j].Observation,
					})
				}
				currentToolCalls = nil
			}
			currentLog = step.Action.Log
		}

		currentToolCalls = append(currentToolCalls, llms.ToolCall{
			ID:   step.Action.ToolID,
			Type: "function",
			FunctionCall: &llms.FunctionCall{
				Name:      step.Action.Tool,
				Arguments: step.Action.ToolInput, // ToolInput is already the raw JSON string
			},
		})
	}

	if len(currentToolCalls) > 0 {
		messages = append(messages, llms.AIChatMessage{
			Content:   currentLog,
			ToolCalls: currentToolCalls,
		})
		for j := len(steps) - len(currentToolCalls); j < len(steps); j++ {
			messages = append(messages, llms.ToolChatMessage{
				ID:      steps[j].Action.ToolID,
				Content: steps[j].Observation,
			})
		}
	}

	return messages
}

func (a *CustomOpenAIAgent) parseOutput(contentResp *llms.ContentResponse) ([]schema.AgentAction, *schema.AgentFinish, error) {
	if contentResp == nil || len(contentResp.Choices) == 0 {
		return nil, nil, fmt.Errorf("no choices in response")
	}
	choice := contentResp.Choices[0]

	if len(choice.ToolCalls) > 0 {
		actions := make([]schema.AgentAction, 0, len(choice.ToolCalls))
		for _, toolCall := range choice.ToolCalls {
			functionName := toolCall.FunctionCall.Name
			toolInputStr := toolCall.FunctionCall.Arguments // Keep the raw arguments JSON string

			contentMsg := "\n"
			if choice.Content != "" {
				contentMsg = fmt.Sprintf("responded: %s\n", choice.Content)
			}

			actions = append(actions, schema.AgentAction{
				Tool:      functionName,
				ToolInput: toolInputStr,
				Log:       fmt.Sprintf("Invoking: %s with %s %s", functionName, toolInputStr, contentMsg),
				ToolID:    toolCall.ID,
			})
		}
		return actions, nil, nil
	}

	return nil, &schema.AgentFinish{
		ReturnValues: map[string]any{
			"output": choice.Content,
		},
		Log: choice.Content,
	}, nil
}

